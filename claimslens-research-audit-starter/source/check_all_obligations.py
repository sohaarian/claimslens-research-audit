#!/usr/bin/env python3
"""Supplement to archived deterministic audit; uses synthetic cases only."""
import copy, importlib.util, json, inspect
from collections import Counter
from datetime import date, timedelta
from pathlib import Path
import claimslens_rule_candidate as corrected
HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('prior',HERE/'claimslens_verifier_historical.py')
prior=importlib.util.module_from_spec(spec);spec.loader.exec_module(prior)
AS_OF=date(2026,10,17)
# Pin the historical module clock without editing the archived source.
class FixedDate(date):
    @classmethod
    def today(cls):
        return cls(2026,10,17)
prior.date = FixedDate

def decisions(core, as_of):
    return {(cid,order['kind']):(core.verify(case,order,as_of=as_of) if 'as_of' in inspect.signature(core.verify).parameters else core.verify(case,order))['eligible_for_simulated_closure'] for cid,case in core.CASES.items() for order in case['orders']}

old=decisions(prior,AS_OF);new=decisions(corrected,AS_OF)
counts=Counter(c['scenario'] for c in corrected.CASES.values())
bykind=Counter(k for (_,k),v in new.items() if v)
# Arithmetic schedule in generate_cases(): 240 records, index i from 0 to 239.
# For 4 non-imaging requirements, supported when i%3==0, i%4==0, i%5==0 or i%3==1.
case=copy.deepcopy(next(c for c in corrected.CASES.values() if c['scenario']=='complete'))
order=case['orders'][0]
proof=next(r for r in case['records'] if r['kind']=='IMAGING' and r['event']=='COMPLETED' and r['authority']=='RADIOLOGY_FINAL')

def cancellation(kind, value=None):
    x=copy.deepcopy(case);c=copy.deepcopy(proof)
    c.update(id='CL-TEST-NEW-CANCEL',event='CANCELLED',date=(date.fromisoformat(proof['date'])+timedelta(days=2)).isoformat())
    if kind=='future': c['date']='2027-01-01'
    if kind=='unparseable': c['date']='not-a-date'
    if kind=='unsigned': c['signed']=False
    if kind=='wrong_authority':c['authority']='SCHEDULING'
    x['records'].append(c)
    d=corrected.verify(x,order,as_of=AS_OF)
    return {'status':d['status'],'closed':d['eligible_for_simulated_closure'],'blockers':d['blockers']}

out={
 'audit_date':AS_OF.isoformat(),
 'original_vs_corrected_all_obligations':{'total':len(old),'changed':sum(old[k]!=new[k] for k in old)},
 'original_vs_corrected_imaging':{'total':240,'changed':sum(old[k]!=new[k] for k in old if k[1]=='IMAGING')},
 'documentarily_met_by_kind':dict(sorted(bykind.items())),
 'scenario_counts':dict(sorted(counts.items())),
 'non_imaging_generator_rule':{'consult':'index modulo 3 equals 0','authorization':'index modulo 4 equals 0','therapy':'index modulo 5 equals 0','work_status':'index modulo 3 equals 1'},
 'cancellation_test_observations':{name:cancellation(name) for name in ('future','unparseable','unsigned','wrong_authority')},
 'note':'These are code-behavior probes, not independent clinical validation; evidence labels generated by the same author.'
}
assert len(old)==len(new)==1200
assert sum(bykind.values())==283
p=HERE/'audit_v6_results.json';p.write_text(json.dumps(out,indent=2,sort_keys=True)+'\n')
print(json.dumps(out,indent=2,sort_keys=True))
